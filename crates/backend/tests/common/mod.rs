/// A freshly-keyed in-memory encrypted File_Store.
#[must_use]
pub fn encrypted_store() -> EncryptedFileStore<InMemoryObjectStore> {
    EncryptedFileStore::new(InMemoryObjectStore::new(), &[5u8; 32])
}

/// Seed a Job (record + spec + encrypted sources) ready for a worker to drain.
pub async fn seed_job(
    store: &EncryptedFileStore<InMemoryObjectStore>,
    backend: &InMemoryJobBackend,
    specs: &InMemorySpecStore,
    token: &str,
    tool: ToolId,
    options: ToolOptions,
    sources: &[Vec<u8>],
    fetched_html: Option<Vec<u8>>,
) {
    let mut source_keys = Vec::new();
    for (i, bytes) in sources.iter().enumerate() {
        let key = scoped_key(token, &format!("src-{i}"));
        let mut nonce = [0u8; 12];
        nonce[0] = i as u8;
        store
            .put_encrypted(&key, &nonce, bytes)
            .await
            .expect("seed source");
        source_keys.push(key);
    }
    backend
        .put(JobRecord {
            job_token: token.to_string(),
            status: JobStatus::Queued,
            output_ids: vec![],
            created_at_ms: 0,
            expires_at_ms: 3_600_000,
        })
        .await
        .expect("seed record");
    specs
        .put_spec(
            token,
            JobSpec {
                tool,
                options,
                source_keys,
                fetched_html,
            },
        )
        .await
        .expect("seed spec");
    backend.enqueue(token).await.expect("enqueue");
}

/// Build a [`Worker`] over the given store / backend / specs / executors.
pub fn worker<'a>(
    store: &'a EncryptedFileStore<InMemoryObjectStore>,
    backend: &'a InMemoryJobBackend,
    specs: &'a InMemorySpecStore,
    ex: &'a Executors,
) -> Worker<'a, InMemoryObjectStore, InMemoryJobBackend, InMemorySpecStore> {
    Worker {
        store,
        jobs: backend,
        specs,
        executors: ex,
        limits: backend::config::SandboxLimits::default(),
    }
}

/// Bundle executors from the three trait objects.
#[must_use]
pub fn executors(
    converter: Arc<dyn backend::convert::Converter>,
    ocr: Arc<dyn backend::ocr::OcrEngine>,
    renderer: Arc<dyn backend::render::PdfRenderer>,
) -> Executors {
    Executors {
        converter,
        ocr,
        renderer,
    }
}
